// Vendored third-party files: cached when present, never blocking the install if one is missing.
const OPTIONAL_VENDOR = [
  './assets/vendor/jszip/jszip.min.js',
];

// Monaco is big (~20 MB), so it is cached in the background after the app has loaded (the page sends
// 'warm-vendor'), in its own cache named after the file list: app releases don't re-download it.
const VENDOR_BASE = './assets/vendor/monaco-editor/';
const VENDOR_PREFIX = 'zern-vendor-';

async function warmVendor() {
  let manifest;
  try { const res = await fetch(VENDOR_BASE + 'precache.json', { cache: 'no-cache' }); if (!res.ok) return; manifest = await res.json(); } catch { return; }
  const name = VENDOR_PREFIX + manifest.version;
  const cache = await caches.open(name);
  const missing = [];
  for (const file of manifest.files) { const url = VENDOR_BASE + 'min/' + file; if (!(await cache.match(url))) missing.push(url); }
  for (let i = 0; i < missing.length; i += 6) await Promise.allSettled(missing.slice(i, i + 6).map((u) => cache.add(u)));
  for (const key of await caches.keys()) if (key.startsWith(VENDOR_PREFIX) && key !== name) await caches.delete(key); // older Monaco
}

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'warm-vendor') event.waitUntil(warmVendor());
});

// Every file of every extension in the registry (extensions/precache.json is generated by `npm run catalog`)
async function precacheExtensions(cache) {
  try {
    const res = await fetch('./extensions/precache.json', { cache: 'reload' });
    if (!res.ok) return;
    const { files } = await res.json();
    await Promise.allSettled(files.map((f) => cache.add(new Request('./extensions/' + f, { cache: 'reload' }))));
  } catch { /* offline install or no list: extensions are cached on first use instead */ }
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(APP_SHELL.map((u) => new Request(u, { cache: 'reload' }))).then(() => Promise.allSettled(OPTIONAL_VENDOR.map((u) => cache.add(u)))).then(() => precacheExtensions(cache)))
      .then(() => self.skipWaiting())
      .catch((err) => console.warn('[sw] Could not fully precache the app shell:', err))
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME && !k.startsWith(VENDOR_PREFIX)).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Virtual HTTP for extensions (e.g. HTML Preview): /__zern_ext__/<extension>/<token>/<path>
// is answered by asking the Zern window that owns <token> for the file.
async function serveFromExtension(event) {
  const u = new URL(event.request.url);
  const rest = u.pathname.slice(u.pathname.indexOf('/__zern_ext__/') + '/__zern_ext__/'.length).split('/');
  const ext = rest.shift(), token = rest.shift(), path = '/' + rest.join('/');
  const wins = (await self.clients.matchAll({ type: 'window' })).filter((c) => !c.url.includes('/__zern_ext__/'));
  if (!wins.length) return new Response('No Zern window is open.', { status: 503 });
  const reply = await new Promise((resolve) => {
    let pending = wins.length;
    const timer = setTimeout(() => resolve(null), 8000);
    wins.forEach((c) => {
      const ch = new MessageChannel();
      ch.port1.onmessage = (e) => {
        if (e.data && e.data.ok) { clearTimeout(timer); resolve(e.data); }
        else if (--pending === 0) { clearTimeout(timer); resolve(null); }
      };
      c.postMessage({ type: 'zern-ext-fetch', ext, token, path: decodeURI(path), search: u.search, method: event.request.method }, [ch.port2]);
    });
  });
  if (!reply) return new Response('Not found', { status: 404 });
  const headers = new Headers(reply.headers || {});
  headers.set('Cache-Control', 'no-store');
  headers.set('Access-Control-Allow-Origin', '*');
  return new Response(reply.body, { status: reply.status || 200, headers });
}

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return; // never intercept writes/uploads
  if (req.url.includes('/__zern_ext__/')) { event.respondWith(serveFromExtension(event)); return; }

  event.respondWith(
    caches.match(req).then((cached) => {
      // Same-origin files are revalidated against the server (not the browser's HTTP cache), so a new
      // release can't be refreshed from a stale copy.
      const networkFetch = fetch(new URL(req.url).origin === self.location.origin ? new Request(req, { cache: 'no-cache' }) : req)
        .then((res) => {
          if (res && res.status === 200) {
            const resClone = res.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(req, resClone));
          }
          return res;
        })
        .catch(() => cached); // offline and not cached: nothing more we can do

      // Serve from cache immediately if we have it (fast + reliable
      // offline); otherwise wait on the network and cache the result
      // for next time.
      return cached || networkFetch;
    })
  );
});
