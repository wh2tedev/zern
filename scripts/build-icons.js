#!/usr/bin/env node
// ============================================================
// build-icons.js - Builds css/icons.css: the app's own icon set.
//
// Zern's icons use their own class prefix (zi / zi-name) and their
// own font-family (zern-icons), so Monaco's ".codicon" classes and
// "codicon" font can never override them or mix with them.
//
// The glyphs come from the Codicons font that is embedded in the
// Monaco copy Zern ships (assets/vendor/monaco-editor), together with
// Monaco's own table of icon names and codes. That keeps the app's
// icons identical to the ones Monaco draws and always up to date with
// the Monaco version in use; there is no separate icon package to
// keep in sync. Run: npm run icons (npm run vendor does it too)
// ============================================================
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const vs = path.join(root, 'assets/vendor/monaco-editor/min/vs');

function buildIcons() {
  const cssFile = path.join(vs, 'editor/editor.main.css');
  if (!fs.existsSync(cssFile)) {
    console.log('- icons.css: Monaco not found in assets/vendor, keeping the current css/icons.css');
    return false;
  }

  // 1) The Codicons font Monaco embeds in its stylesheet
  const css = fs.readFileSync(cssFile, 'utf8');
  const face = /@font-face\s*\{[^}]*font-family:\s*"?codicon"?[^}]*\}/.exec(css);
  const data = face && /url\(["']?(data:[^;]+;base64,[A-Za-z0-9+/=]+)/.exec(face[0]);
  if (!data) throw new Error('Could not find the embedded Codicons font in Monaco\'s editor.main.css.');

  // 2) Monaco's table of icon names -> codes, e.g. ("source-control",60008); aliases look like ("tree-item-expanded","chevron-down")
  const chunk = fs.readdirSync(vs).filter((f) => f.endsWith('.js')).find((f) => /"source-control",\d{5}\)/.test(fs.readFileSync(path.join(vs, f), 'utf8')));
  if (!chunk) throw new Error('Could not find Monaco\'s icon table (format changed?).');
  const src = fs.readFileSync(path.join(vs, chunk), 'utf8');
  // Same rules as Monaco: entries are read in order, the last definition of a name wins, and an alias takes the code of its target.
  // Codes are 5-digit decimals (60008), except the very first one, minified as 6e4; shorter numbers belong to other tables.
  const codes = new Map();
  for (const m of src.matchAll(/\("([a-z0-9-]+)",(?:(\d{5}|\de\d)|"([a-z0-9-]+)")\)/g)) {
    if (m[2] !== undefined) codes.set(m[1], Number(m[2]));
    else if (codes.has(m[3])) codes.set(m[1], codes.get(m[3]));
  }
  if (codes.size < 300) throw new Error(`Only ${codes.size} icons found in Monaco's table; its format may have changed.`);

  const out = [
    '/* GENERATED by scripts/build-icons.js from the Monaco copy in assets/vendor - do not edit. Run `npm run icons` to rebuild.',
    '   Icons: Codicons by Microsoft (https://github.com/microsoft/vscode-codicons), CC BY 4.0; font code MIT.',
    '   Zern uses its own class prefix (zi-) and font (zern-icons) so Monaco\'s ".codicon" rules can never affect it. */',
    `@font-face{font-family:"zern-icons";src:url(${data[1]}) format("truetype");font-display:block}`,
    '.zi{font:normal normal 16px/1 zern-icons;display:inline-block;text-decoration:none;text-rendering:auto;text-align:center;text-transform:none;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale;user-select:none;-webkit-user-select:none}',
    '.zi-modifier-spin,.zi-loading{animation:zi-spin 1.5s steps(30) infinite}',
    '@keyframes zi-spin{100%{transform:rotate(360deg)}}',
  ];
  for (const [name, code] of codes) out.push(`.zi-${name}::before{content:"\\${code.toString(16)}"}`);
  fs.writeFileSync(path.join(root, 'css/icons.css'), out.join('\n') + '\n');
  console.log(`+ css/icons.css: ${codes.size} icons (from ${chunk})`);
  return true;
}

module.exports = { buildIcons };
if (require.main === module) buildIcons();
