#!/usr/bin/env node
// ============================================================
// build-catalog.js - Bundles the extension catalog (registry,
// manifests, README and CHANGELOG of every extension) into
// extensions/catalog.js. The desktop app (file://) imports it as a
// module because fetch() on local files is not reliable there; the web
// version reads the JSON files directly. Run: npm run catalog
// ============================================================
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'extensions');
const registry = JSON.parse(fs.readFileSync(path.join(dir, 'registry.json'), 'utf8'));
const read = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : null);

const manifests = {}, docs = {};
for (const entry of registry.extensions) {
  const base = path.join(dir, entry.dir);
  const manifest = JSON.parse(fs.readFileSync(path.join(base, 'zern-extension.json'), 'utf8'));
  manifests[entry.dir] = manifest;
  docs[entry.dir] = { readme: manifest.readme ? read(path.join(base, manifest.readme)) : null, changelog: manifest.changelog ? read(path.join(base, manifest.changelog)) : null };
}

// File list for the service worker (offline cache): every file of every listed extension
const files = [];
for (const entry of registry.extensions) {
  (function walk(d, rel) {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (e.isDirectory()) walk(path.join(d, e.name), `${rel}/${e.name}`);
      else files.push(`${rel}/${e.name}`);
    }
  })(path.join(dir, entry.dir), entry.dir);
}
const precacheText = JSON.stringify({ files: files.sort() }) + '\n';

const out = `// GENERATED by scripts/build-catalog.js - do not edit. Run \`npm run catalog\` after changing an extension.\nexport default ${JSON.stringify({ registry, manifests, docs }, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const same = read(path.join(dir, 'precache.json')) === precacheText && read(path.join(dir, 'catalog.js')) === out;
  console.log(same ? 'catalog: up to date' : 'catalog: OUT OF DATE, run `npm run catalog`');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(path.join(dir, 'precache.json'), precacheText);
fs.writeFileSync(path.join(dir, 'catalog.js'), out);
console.log(`catalog.js: ${registry.extensions.length} extension(s) bundled, precache.json: ${files.length} files`);
